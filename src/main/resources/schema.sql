CREATE TABLE IF NOT EXISTS app_users (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 username VARCHAR(40) NOT NULL UNIQUE,
 full_name VARCHAR(160) NOT NULL,
 email VARCHAR(180), phone VARCHAR(30), address VARCHAR(300),
 password_hash VARCHAR(100) NOT NULL,
 role VARCHAR(24) NOT NULL DEFAULT 'READER',
 active BOOLEAN NOT NULL DEFAULT TRUE,
 banned_until TIMESTAMP NULL,
 deleted_at TIMESTAMP NULL,
 created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL
);
CREATE TABLE IF NOT EXISTS books (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 title VARCHAR(220) NOT NULL,
 title_kk VARCHAR(220),title_ru VARCHAR(220),title_en VARCHAR(220),
 author VARCHAR(180) NOT NULL,
 genre VARCHAR(80) NOT NULL DEFAULT 'Other',
 language VARCHAR(6) NOT NULL DEFAULT 'en',
 description VARCHAR(4000),
 cover_url VARCHAR(800),
 copies INT NOT NULL DEFAULT 0,
 content BYTEA,
 content_type VARCHAR(100),
 is_public BOOLEAN NOT NULL DEFAULT TRUE,
 created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE IF NOT EXISTS reservations (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 user_id BIGINT NOT NULL REFERENCES app_users(id),
 book_id BIGINT NOT NULL REFERENCES books(id),
 pickup_day DATE NOT NULL,
 due_day DATE NULL,
 qr_code VARCHAR(60) NOT NULL UNIQUE,
 status VARCHAR(20) NOT NULL DEFAULT 'RESERVED',
 renewed BOOLEAN NOT NULL DEFAULT FALSE,
 created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE IF NOT EXISTS waitlist (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 user_id BIGINT NOT NULL REFERENCES app_users(id),
 book_id BIGINT NOT NULL REFERENCES books(id),
 status VARCHAR(20) NOT NULL DEFAULT 'WAITING',
 offer_reservation_id BIGINT NULL REFERENCES reservations(id),
 created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE IF NOT EXISTS favorites (
 user_id BIGINT NOT NULL REFERENCES app_users(id),
 book_id BIGINT NOT NULL REFERENCES books(id),
 created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 PRIMARY KEY(user_id,book_id)
);
CREATE TABLE IF NOT EXISTS reading_progress (
 user_id BIGINT NOT NULL REFERENCES app_users(id),
 book_id BIGINT NOT NULL REFERENCES books(id),
 percentage INT NOT NULL DEFAULT 0,
 updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 PRIMARY KEY(user_id,book_id)
);
CREATE TABLE IF NOT EXISTS reviews (
 user_id BIGINT NOT NULL REFERENCES app_users(id),
 book_id BIGINT NOT NULL REFERENCES books(id),
 rating INT NOT NULL,
 body VARCHAR(1000),
 created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 PRIMARY KEY(user_id,book_id)
);
CREATE TABLE IF NOT EXISTS notifications (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 user_id BIGINT NOT NULL REFERENCES app_users(id),
 message_kk VARCHAR(500) NOT NULL,
 message_ru VARCHAR(500) NOT NULL,
 message_en VARCHAR(500) NOT NULL,
 seen BOOLEAN NOT NULL DEFAULT FALSE,
 created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE IF NOT EXISTS audit_log (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 actor_id BIGINT NULL REFERENCES app_users(id),
 action VARCHAR(70) NOT NULL,
 subject_type VARCHAR(30) NOT NULL,
 subject_id BIGINT,
 detail VARCHAR(500),
 created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS ix_reservations_book_status ON reservations(book_id,status);
CREATE INDEX IF NOT EXISTS ix_reservations_user ON reservations(user_id);
CREATE INDEX IF NOT EXISTS ix_waitlist_book_status ON waitlist(book_id,status);
CREATE INDEX IF NOT EXISTS ix_notifications_user ON notifications(user_id,created_at);

-- Records one-time catalog revisions without deleting user records or loan history.
CREATE TABLE IF NOT EXISTS paraq_migrations (
 migration_key VARCHAR(90) PRIMARY KEY,
 applied_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
